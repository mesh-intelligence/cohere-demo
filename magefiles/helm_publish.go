package main

import (
	"encoding/base64"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
)

// The packaged chart is the installable artifact: packaging vendors the
// agent-services library and stages the canonical composition, so an installer
// needs no Go modules and no org access (GH-936, the GH-928 decision). The
// chart version carries the pinned declarative-agents release as a prerelease
// identifier -- 0.1.0-v0.20261005.0 -- so the OCI tag says which release the
// packaged defaults pull, a republish of the same pin is explicit and
// detectable, and a pin bump cannot silently overwrite the prior version.
const (
	chartOCIRepository = "oci://ghcr.io/mesh-intelligence/cohere-demo/charts"
	chartPublishName   = "chatbot-mesh"
	// chartPublishReleaseName is the release name the published artifacts are
	// built for. The externalized UI ConfigMap names carry the release name,
	// so an install of the published chart must use this one; the deploy/
	// README says so.
	chartPublishReleaseName = "cohere-demo"
	chartPublishDeployDir   = "deploy"
)

// helmRunner runs one helm command and returns its combined output; tests
// substitute a recorder.
type helmRunner func(args ...string) ([]byte, error)

func helmCommandRun(args ...string) ([]byte, error) {
	return exec.Command("helm", args...).CombinedOutput()
}

// Publish packages the chart exactly as helm:package does -- vendored
// agent-services, staged composition, the same validations -- at the
// pin-derived version, and pushes it to the public OCI repository. A version
// already present upstream is left alone. Pushing needs a helm registry login
// to ghcr.io with write:packages; the verb reads no credential itself.
func (Helm) Publish() error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	return publishChatbotChart(helmCommandRun, func(destination, version string) error {
		return packageChatbotChartForPublish(root, destination, version)
	}, root)
}

// packageChatbotChartForPublish stages the chart exactly as helm:package does,
// then externalizes the UI bundles at the documented release name before
// packaging -- the full chart's Helm release secret is over Kubernetes' 1MiB
// object cap, the same arithmetic that makes app:up externalize
// (applier_release_budget.go). The archives land beside the repository as
// deploy/ui-assets.yaml (the two out-of-release ConfigMaps) and
// deploy/ui-assets-values.yaml (the values that point the chart at them), so
// an installer applies one manifest and passes one extra values file.
func packageChatbotChartForPublish(root, destination, version string) error {
	chartDir := filepath.Join(root, "helm")
	catalogRoot, err := resolveCatalogRoot("chatbot-mesh helm publish", root)
	if err != nil {
		return err
	}
	staged, cleanup, err := stagePackageChart(chartDir, root, catalogRoot)
	if err != nil {
		return err
	}
	defer cleanup()
	if err := validateStagedChatbotChart(staged); err != nil {
		return err
	}
	assets, assetsCleanup, err := externalizeUIAssets(staged, chartPublishReleaseName)
	if err != nil {
		return err
	}
	defer assetsCleanup()
	if err := writePublishedUIAssets(root, assets); err != nil {
		return err
	}
	if _, err := packageStagedChatbotChart(staged, destination, version); err != nil {
		return err
	}
	return nil
}

// writePublishedUIAssets renders the externalized archives as tracked
// manifests: the ConfigMaps an installer applies before the install, and the
// values file that points the chart at them.
func writePublishedUIAssets(root string, assets []externalUIAsset) error {
	deployDir := filepath.Join(root, chartPublishDeployDir)
	if err := os.MkdirAll(deployDir, 0o755); err != nil {
		return err
	}
	manifests := "# Out-of-release UI asset ConfigMaps for the published chatbot-mesh chart\n" +
		"# (GH-936). Generated by mage helm:publish from the committed bundles; the\n" +
		"# names carry the content checksum and the release name `" + chartPublishReleaseName + "`,\n" +
		"# which an install of the published chart must use. Apply into the install\n" +
		"# namespace before `helm install`, together with ui-assets-values.yaml.\n"
	values := "# Values companion to ui-assets.yaml (GH-936): points the chart at the\n" +
		"# out-of-release UI ConfigMaps. Generated by mage helm:publish.\n"
	for _, asset := range assets {
		archive, err := os.ReadFile(asset.Archive)
		if err != nil {
			return err
		}
		manifests += "---\napiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: " + asset.ConfigMapName + "\n" +
			"  labels:\n    app.kubernetes.io/part-of: chatbot-mesh\n" +
			"binaryData:\n  assets.tgz: " + base64.StdEncoding.EncodeToString(archive) + "\n"
		values += asset.Component + ":\n  uiArchiveConfigMap: " + asset.ConfigMapName + "\n" +
			"  uiArchiveChecksum: " + asset.Checksum + "\n"
	}
	if err := os.WriteFile(filepath.Join(deployDir, "ui-assets.yaml"), []byte(manifests), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(deployDir, "ui-assets-values.yaml"), []byte(values), 0o644)
}

// chartPublishVersion derives the published chart version from the pinned
// declarative-agents release.
func chartPublishVersion(root string) (string, error) {
	tag, _, err := pinnedDeclarativeAgentsRelease(root)
	if err != nil {
		return "", err
	}
	return "0.1.0-" + tag, nil
}

func publishChatbotChart(helm helmRunner, pack func(destination, version string) error, root string) error {
	version, err := chartPublishVersion(root)
	if err != nil {
		return err
	}
	reference := chartOCIRepository + "/" + chartPublishName
	if _, err := helm("show", "chart", reference, "--version", version); err == nil {
		fmt.Printf("helm:publish: %s version %s is already published\n", reference, version)
		return nil
	}
	destination, err := os.MkdirTemp("", "chatbot-mesh-publish-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(destination) }()
	if err := pack(destination, version); err != nil {
		return err
	}
	archive := filepath.Join(destination, chartPublishName+"-"+version+".tgz")
	if out, err := helm("push", archive, chartOCIRepository); err != nil {
		return fmt.Errorf("helm push %s: %w: %s", archive, err, tailOfOutput(string(out)))
	}
	if out, err := helm("show", "chart", reference, "--version", version); err != nil {
		return fmt.Errorf("helm:publish: %s version %s is not readable after the push: %w: %s",
			reference, version, err, tailOfOutput(string(out)))
	}
	fmt.Printf("helm:publish: published %s version %s\n", reference, version)
	return nil
}
